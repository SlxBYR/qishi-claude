/// Picks the display string for the current interface language.
func L(_ zh: String, _ en: String) -> String { Loc.language == .en ? en : zh }

/// Translates a Chinese string produced by model code. A "前缀：详情" message
/// keeps its (possibly system-provided) detail and translates what it can.
func LT(_ zh: String) -> String {
    guard Loc.language == .en else { return zh }
    if let english = Loc.english[zh] { return english }
    if let separator = zh.range(of: "："), let prefix = Loc.english[String(zh[..<separator.lowerBound])] {
        return prefix + ": " + LT(String(zh[separator.upperBound...]))
    }
    return zh
}

extension Date {
    /// Date text in the interface language rather than the system locale.
    func qishiFormatted(date: Date.FormatStyle.DateStyle = .abbreviated, time: Date.FormatStyle.TimeStyle = .shortened) -> String {
        formatted(Date.FormatStyle(date: date, time: time, locale: Loc.locale))
    }
}
